eq('一2 积分后导数校验',diff(f(t+b),t),Subs(Derivative(f(t),t),t,t+b))
eq('一3 阶跃跳变不能遗漏',1+lt(-3*exp(-3*t)),s*lt(exp(-3*t)))
eq('一5 连续基本周期',2*pi/Integer(1),2*pi)
check('一5 离散非周期',pi.is_irrational)
eq('一6 指数 LT',lt(exp(-2*t)),1/(s+2))
eq('一7 无失真相位',exp(-I*w*b),cos(w*b)-I*sin(w*b))
eq('一8 余弦分解',(exp(I*b*t)+exp(-I*b*t))/2,cos(b*t))
eq('二1 先提尺度再时移',-2*(t-Rational(5,2)),5-2*t)
eq('二2 由输出反求输入',(1/((I*w+2)*(I*w+3)))/(1/(I*w+2)),1/(I*w+3))
