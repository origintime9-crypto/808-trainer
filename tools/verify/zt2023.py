eq('二7 有限窗 LT',integrate(exp(-s*t),(t,0,1)),(1-exp(-s))/s)
eq('三1 反褶斜段',((t+1).subs(t,2-t)),3-t)
check('三1 区间反射',sorted([2-(-1),2-0])==[2,3] and sorted([2-0,2-1])==[1,2])
