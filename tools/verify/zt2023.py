# 三年共用的四道零极点综合题，避免把 h(0+) 与 H(0) 混用。
H=2*s/(s**2+2*s+Rational(7,4))
check('四1 复极点',roots(s**2+2*s+Rational(7,4),s)=={-1+I*sqrt(3)/2,-1-I*sqrt(3)/2})
eq('四1 初值确定增益',limit(s*H,s,oo),Integer(2))
eq('四2 频率响应',H.subs(s,I*w),2*I*w/(Rational(7,4)-w**2+2*I*w))
ht=exp(-t)*(2*cos(sqrt(3)*t/2)-4*sqrt(3)/3*sin(sqrt(3)*t/2))
eq('四3 修正正弦余弦项',lt(ht),H)
eq('四3 时域初值',limit(ht,t,0),Integer(2))
Hj=H.subs(s,I*sqrt(3)/2)
eq('四4 正弦幅度',Abs(Hj),sqrt(3)/2)
eq('四4 正弦相角',arg(Hj),pi/6)
finish()
