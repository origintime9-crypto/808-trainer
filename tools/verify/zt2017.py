"""2017 印刷卷：符号变换、节点方程、劳斯及离散递推复核。"""
from common import *

eq('一1 正弦稳态幅度', 5/sqrt(4**2+2**2), sqrt(5)/2)
eq('一1 相位', arg(1/(4+2*I)), -atan(Rational(1,2)))
eq('一2 变换的尺度与延时', (2*t-9).subs(t,t+Rational(9,2)), 2*t)
eq('一4 冲激筛选1', exp(-t).subs(t,-3), exp(3))
eq('一4 冲激筛选2', limit(t+exp(-t)*sin(pi*t)/(t-1),t,1), 1-pi/exp(1))
b = Symbol('b', positive=True)
eq('一6 矩形谱逆变换', integrate(exp(I*w*t),(w,-2*b,2*b))/(2*pi), sin(2*b*t)/(pi*t))
check('一7 基波频率', Rational(1,50)**-1==50 and Rational(1,200)**-1==200)
eq('一8 余弦分解调制', expand_complex((exp(I*b*t)+exp(-I*b*t))/2), cos(b*t))
eq('一9 低通口径抽样周期', 1/(2*Integer(10000)), Rational(50,10**6))
eq('一10 逆拉氏', lt(4*exp(-t)-3*exp(-2*t)), (s+5)/((s+1)*(s+2)))

zi,zs = symbols('zi zs')
sol=solve([zi+zs-(2*exp(-2*t)+sin(2*t)),zi+2*zs-(2*exp(-2*t)+2*sin(2*t))],[zi,zs])
eq('二1 零输入',sol[zi],2*exp(-2*t));eq('二1 零状态',sol[zs],sin(2*t))
K=Symbol('K',real=True)
G=1/((s+2)*(s+4))
eq('二2 闭环', G/(1+G*K/s), s/(s**3+6*s**2+8*s+K))
check('二2 劳斯第一列', reduce_inequalities([K>0,(48-K)/6>0],K).as_set()==Interval.open(0,48))
eq('二2 K=0 时的消去', (s/(s**3+6*s**2+8*s)).cancel(), G)
yn=lambda j: 3*(Rational(1,2)**j-Rational(1,3)**j)*u(j)
recurrence('二3 输入起点 n=1',yn,[1,Rational(-1,3)],lambda j:Rational(1,2)**j*u(j-1))

H=1+1/((s+1)*(s+2))
eq('三1 修正 h 指数符号', lt(exp(-t)-exp(-2*t)),H-1)
eq('三2 阶跃',lt(Rational(3,2)-exp(-t)+exp(-2*t)/2),H/s)
check('三3 零点',roots(s**2+3*s+3,s)=={(-3+I*sqrt(3))/2,(-3-I*sqrt(3))/2})
eq('三4 微分方程系数',H,(s**2+3*s+3)/(s**2+3*s+2))
eq('三5 频率响应',H.subs(s,I*w),(3-w**2+3*I*w)/(2-w**2+3*I*w))
eq('四1 矩形谱逆变换',integrate(pi*exp(I*w*t),(w,-1,1))/(2*pi),sin(t)/t)
eq('四2 狄利克雷积分',integrate(sin(t)/t,(t,0,oo))*2,pi)

Hz=(1+7/z)/(1+4/z+6/z**2)
eq('五3 框图系统函数',Hz,z*(z+7)/(z**2+4*z+6))
check('五5 极点与模',set(solve(z**2+4*z+6,z))=={-2+I*sqrt(2),-2-I*sqrt(2)} and Abs(-2+I*sqrt(2))==sqrt(6))
# 使用共轭极点形式独立复核三角函数表示，以免浮点 arccos 引入误差。
rp,rm=-2+I*sqrt(2),-2-I*sqrt(2)
hn=lambda j:simplify((rp**j+rm**j)/2+Rational(5,1)/(2*I*sqrt(2))*(rp**j-rm**j))*u(j)
recurrence('五1 因果冲激响应',hn,[1,4,6],lambda j:Integer(j==0)+7*Integer(j==1))
check('五1 起始值', [hn(j) for j in range(3)]==[1,3,-18])
check('五6 极点在单位圆外', sqrt(6)>1)

H=(s+5)/(s**2+5*s+6)
check('六1 零极点', roots(s+5,s)=={-5} and roots(s**2+5*s+6,s)=={-2,-3})
eq('六3 h(t)',lt(3*exp(-2*t)-2*exp(-3*t)),H)
eq('六4 频率响应',H.subs(s,I*w),(5+I*w)/(6-w**2+5*I*w))
finish()
