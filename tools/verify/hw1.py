from common import *
v = Symbol('v', real=True)
a = Symbol('a', real=True)
T = Symbol('T', positive=True)
w0 = Symbol('w0', real=True)

eq('1.1(a) 饱和斜坡 t>1', v-(v-1), 1)
eq('1.1(b) 三个冲激强度总和', -1+1-1, -1)
f = exp(-v)*cos(2*pi*v)
eq('1.2(1) 左内侧', f.subs(v,1), exp(-1))
eq('1.2(1) 右内侧', f.subs(v,2), exp(-2))
check('1.2(1) 两个区间内零点', all(simplify(f.subs(v,q))==0 for q in [Rational(5,4),Rational(7,4)]))
eq('1.2(2) 截断三角中心', (1-Abs(v)/2).subs(v,0), 1)
eq('1.2(2) 截断三角边缘', (1-Abs(v)/2).subs(v,1), Rational(1,2))
check('1.2(3) 有限交错和', all(sum((-1)**k for k in range(j+1))==(1 if j%2==0 else 0) for j in range(12)))
check('1.2(3) 相位相消', all(trigsimp(expand_trig(sin(pi*(v-k))-(-1)**k*sin(pi*v)))==0 for k in range(5)))
check('1.2(4) 整数阶跃计数', all(sum(1 for j in range(1,20) if Rational(4*k+1,4)>j)==k for k in range(8)))
check('1.2(5) 符号方波样点', all(sign(sin(pi*(Rational(1,2)+k)))==Integer(-1)**k for k in range(-5,6)))
eq('1.2(6) 原题从零开始', sin(4*pi*v/T).subs(v,0), 0)
eq('1.2(6) 1/8 周期正峰', sin(4*pi*v/T).subs(v,T/8), 1)
check('1.2(6) 五个零点', all(simplify(sin(4*pi*q))==0 for q in [0,Rational(1,4),Rational(1,2),Rational(3,4),1]))
eq('1.4(1) 筛选', (v-a).subs(v,0), -a)
eq('1.4(2) 可去极限含系数 2', 2*limit(sin(2*v)/v,v,0), 4)
eq('1.4(3) 非零筛选位置', a-a/3, 2*a/3)
eq('1.4(4) 原题减号', (v-sin(v)).subs(v,pi/6), pi/6-Rational(1,2))
eq('1.4(5) 指数筛选差', exp(I*w0*0)-exp(I*w0*a), 1-exp(I*w0*a))
delta_roots=[-3*pi/2,-pi/2,pi/2,3*pi/2]
check('1.4(6) 四个单根及雅可比', all(cos(q)==0 and Abs(sin(q))==1 for q in delta_roots))
eq('1.4(6) 冲激根求和', sum(1+q for q in delta_roots), 4)
eq('1.4(7) 尺度后的冲激强度', 2/Abs(Integer(-2)), 1)
check('1.13(1) 零输入反例', cos(0)!=0)
eq('1.13(2) 固定系数满足叠加', (2*v+3*v**2)*cos(v), 2*v*cos(v)+3*v**2*cos(v))
eq('1.13(3) 微分和时移交换', diff((v-a)**3,v), (diff(v**3,v)).subs(v,v-a))
check('1.13(4) 平方违反齐次性', Integer(2)**2!=2*Integer(1)**2)
check('1.13(5) 移位积分上限不同', 5*v-a != 5*(v-a))
eq('1.13(6) 固定时移交换', ((v/3+(v+2)**2).subs(v,v-a)), (v-a)/3+(v-a+2)**2)
check('1.13(7) 绝对值负齐次反例', Abs(-1)!=-Abs(1))
check('1.13(8) 半周期延时改变采样位置', T/2!=0)
x = Function('x')
eq('1.15(1) 延时逆操作', (v-3).subs(v,v+3), v)
check('1.15(2) 两个不同常数输入同输出', diff(Integer(0),v)==diff(Integer(1),v)==0)
eq('1.15(3) 固定边界积分的微分', diff(Integral(exp(tau),(tau,-oo,v)),v), exp(v))
eq('1.15(4) 连续尺度逆操作', (5*v).subs(v,v/5), v)
finish()
