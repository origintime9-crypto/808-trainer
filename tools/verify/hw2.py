"""老师指定 2.12 的六个卷积，积分独立复核。"""
from common import *
a = Symbol('a', positive=True)
w0 = Symbol('w0', positive=True)
A,C = symbols('A C', real=True)
v = Symbol('v', real=True)
q1 = A*C*(sin(w0*v)*integrate(exp(-a*tau)*cos(w0*tau),(tau,0,oo))
            - cos(w0*v)*integrate(exp(-a*tau)*sin(w0*tau),(tau,0,oo)))
eq('2.12(1) 全时域正弦卷积', q1, A*C*(a*sin(w0*v)-w0*cos(w0*v))/(a*a+w0*w0))
eq('2.12(2) 因果积分', integrate(exp(-a*tau),(tau,0,t)), (1-exp(-a*t))/a)
eq('2.12(3) 冲激卷积', cos(w0*(v-0)+pi/4), cos(w0*v+pi/4))
eq('2.12(4) 上升段', integrate(1+tau,(tau,0,v-1)), (v*v-1)/2)
eq('2.12(4) 下降段', integrate(1+tau,(tau,v-2,1)), -v*v/2+v+Rational(3,2))
eq('2.12(4) 峰值连续', ((v*v-1)/2).subs(v,2), (-v*v/2+v+Rational(3,2)).subs(v,2))
eq('2.12(4) 面积乘积', integrate((v*v-1)/2,(v,1,2))+integrate(-v*v/2+v+Rational(3,2),(v,2,3)), Rational(3,2))
eq('2.12(5) 提前减延时', expand_trig(cos(w0*(v+1))-cos(w0*(v-1))), -2*sin(w0*v)*sin(w0))
eq('2.12(6) t<1 的积分', integrate(exp(v-tau),(tau,2,oo)), exp(v-2))
eq('2.12(6) t>=1 的积分', integrate(exp(v-tau),(tau,v+1,oo)), exp(-1))
eq('2.12(6) 分界处连续', exp(v-2).subs(v,1), exp(-1))
finish()
